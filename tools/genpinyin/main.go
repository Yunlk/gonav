// Command genpinyin 把 pinyin-data 的汉字读音表压缩生成 internal/pinyin/table_gen.go。
//
// 数据源：https://cdn.jsdelivr.net/gh/mozillazg/pinyin-data@master/pinyin.txt（Unicode 读音整理，MIT）
//
//	go run ./tools/genpinyin -src tools/pinyin.txt -out internal/pinyin/table_gen.go
package main

import (
	"bytes"
	"compress/gzip"
	"encoding/base64"
	"encoding/binary"
	"flag"
	"fmt"
	"log"
	"os"
	"sort"
	"strconv"
	"strings"
)

// toneFold 把带声调的韵母折叠为基础字母；ü 统一写作 v。
var toneFold = map[rune]string{
	'ā': "a", 'á': "a", 'ǎ': "a", 'à': "a",
	'ē': "e", 'é': "e", 'ě': "e", 'è': "e", 'ê': "e",
	'ī': "i", 'í': "i", 'ǐ': "i", 'ì': "i",
	'ō': "o", 'ó': "o", 'ǒ': "o", 'ò': "o",
	'ū': "u", 'ú': "u", 'ǔ': "u", 'ù': "u",
	'ǖ': "v", 'ǘ': "v", 'ǚ': "v", 'ǜ': "v", 'ü': "v",
	'ń': "n", 'ň': "n", 'ǹ': "n",
	'ḿ': "m",
}

func normalize(reading string) string {
	var b strings.Builder
	for _, r := range reading {
		if fold, ok := toneFold[r]; ok {
			b.WriteString(fold)
			continue
		}
		switch {
		case r >= 'a' && r <= 'z':
			b.WriteByte(byte(r))
		case r >= 'A' && r <= 'Z':
			b.WriteByte(byte(r - 'A' + 'a'))
		}
	}
	return b.String()
}

func main() {
	src := flag.String("src", "tools/pinyin.txt", "pinyin-data 文本路径")
	out := flag.String("out", "internal/pinyin/table_gen.go", "生成文件路径")
	flag.Parse()

	raw, err := os.ReadFile(*src)
	if err != nil {
		log.Fatalf("读取 %s: %v", *src, err)
	}

	readings := map[rune]string{}
	for _, line := range strings.Split(string(raw), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		colon := strings.Index(line, ":")
		if colon < 0 || !strings.HasPrefix(line, "U+") {
			continue
		}
		code, err := strconv.ParseInt(strings.TrimPrefix(line[:colon], "U+"), 16, 32)
		if err != nil {
			continue
		}
		body := line[colon+1:]
		if hash := strings.Index(body, "#"); hash >= 0 {
			body = body[:hash]
		}
		first := strings.TrimSpace(strings.Split(strings.TrimSpace(body), ",")[0])
		syllable := normalize(first)
		if syllable == "" {
			continue
		}
		readings[rune(code)] = syllable
	}
	if len(readings) == 0 {
		log.Fatalf("%s 中没有解析到任何读音", *src)
	}

	runes := make([]rune, 0, len(readings))
	for r := range readings {
		runes = append(runes, r)
	}
	sort.Slice(runes, func(i, j int) bool { return runes[i] < runes[j] })

	syllables := make([]string, 0, 512)
	syllIndex := map[string]int{}
	for _, r := range runes {
		s := readings[r]
		if _, ok := syllIndex[s]; !ok {
			syllIndex[s] = len(syllables)
			syllables = append(syllables, s)
		}
	}

	var buf bytes.Buffer
	writeUvarint(&buf, uint64(len(runes)))
	prev := rune(0)
	for _, r := range runes {
		writeUvarint(&buf, uint64(r-prev))
		writeUvarint(&buf, uint64(syllIndex[readings[r]]))
		prev = r
	}
	writeUvarint(&buf, uint64(len(syllables)))
	for _, s := range syllables {
		writeUvarint(&buf, uint64(len(s)))
		buf.WriteString(s)
	}

	var gz bytes.Buffer
	zw, err := gzip.NewWriterLevel(&gz, gzip.BestCompression)
	if err != nil {
		log.Fatal(err)
	}
	if _, err := zw.Write(buf.Bytes()); err != nil {
		log.Fatal(err)
	}
	if err := zw.Close(); err != nil {
		log.Fatal(err)
	}

	encoded := base64.StdEncoding.EncodeToString(gz.Bytes())
	var file strings.Builder
	file.WriteString("// Code generated by tools/genpinyin from mozillazg/pinyin-data; DO NOT EDIT.\n\n")
	file.WriteString("package pinyin\n\n")
	file.WriteString("// tableGzipBase64 是「码点 + 音节索引 + 音节表」打包后的 gzip/base64 数据。\n")
	file.WriteString("const tableGzipBase64 = \"\" +\n")
	const chunk = 120
	for i := 0; i < len(encoded); i += chunk {
		end := min(i+chunk, len(encoded))
		fmt.Fprintf(&file, "\t%q +\n", encoded[i:end])
	}
	file.WriteString("\t\"\"\n")

	if err := os.WriteFile(*out, []byte(file.String()), 0o644); err != nil {
		log.Fatalf("写入 %s: %v", *out, err)
	}
	fmt.Printf("生成 %s：%d 个汉字，%d 个音节，原始 %d 字节 → 压缩后 %d 字节\n",
		*out, len(runes), len(syllables), buf.Len(), gz.Len())
}

func writeUvarint(buf *bytes.Buffer, v uint64) {
	var tmp [binary.MaxVarintLen64]byte
	n := binary.PutUvarint(tmp[:], v)
	buf.Write(tmp[:n])
}
