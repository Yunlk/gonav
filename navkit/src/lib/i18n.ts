const dict: Record<Locale, Record<string, string>> = { "zh-CN": zh, en };

/** 按当前 locale 翻译，支持 {name} 占位。缺 key 时回落到中文，再回落 key 本身。 */
export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const template = dict[locale]?.[key] ?? zh[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

/** 组件里用这个：跟随 profile.locale，切换语言立刻生效。 */
export function useT(): (key: string, vars?: Record<string, string | number>) => string {
  const locale = useNavkit((s) => s.profile?.locale ?? "zh-CN");
  return (key, vars) => translate(locale, key, vars);
}

